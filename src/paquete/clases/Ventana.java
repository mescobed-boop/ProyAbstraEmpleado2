    public void CargarTabla()
    {
        int fila = this.jTable1.getRowCount();
        for(int i=0;i<fila;i++)
        {
            modelo.removeRow(0);
        }
        
        Empleado[] arreglo = refG.getArreglo();
        String[] datos = new String[6];
        for(int i=0;i<refG.getPuntero();i++)
        {
            if(arreglo[i] instanceof Administrativo)
            {
                datos[0]="Admin";
            }
            else if(arreglo[i] instanceof Electronico)
            {
                datos[0]="Elec";
            }
            else if(arreglo[i] instanceof Programador)
            {
                datos[0]="Progra";
            }
            datos[1]=arreglo[i].getNom();
            datos[2]=arreglo[i].getDire();
            datos[3]= String.valueOf(arreglo[i].getSueldoB());
            datos[4]=String.valueOf(arreglo[i].getBono());
            datos[5]=String.valueOf(arreglo[i].getSueldoP());
            
            modelo.addRow(datos);
        }
        
        
        
        
    }
    
    
